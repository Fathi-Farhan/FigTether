#!/bin/sh
# Print the release evidence template for the current working tree.
#
# The template follows the release evidence template of PRD Appendix C and the
# release candidate checklist in docs/07-ops/04-release-process.md. The commit,
# the artifact hashes, and the schema version are filled in automatically; the
# remaining fields are for a human to complete after a real run.
#
# POSIX sh, no bashisms. The PowerShell twin with the same behaviour is
# scripts/release-evidence.ps1.
#
# Usage: sh scripts/release-evidence.sh [artifact-directory]
#        the artifact directory defaults to artifacts/release

set -eu

root="$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)"
cd "$root"

artifact_dir="${1:-artifacts/release}"

commit="unknown"
if git rev-parse --git-dir >/dev/null 2>&1; then
	head="$(git rev-parse --verify HEAD 2>/dev/null || true)"
	if [ -n "$head" ]; then
		commit="$head"
		branch="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
		if [ -n "$branch" ]; then
			commit="$commit (branch $branch)"
		fi
	else
		commit="unknown (no commit yet)"
	fi
fi

schema_version="unknown"
if [ -f crates/model/src/lib.rs ]; then
	schema_version="$(sed -n 's/^pub const SCHEMA_VERSION: &str = "\(.*\)";$/\1/p' crates/model/src/lib.rs | head -n 1)"
	if [ -z "$schema_version" ]; then
		schema_version="unknown"
	fi
fi

hash_of() {
	if command -v sha256sum >/dev/null 2>&1; then
		sha256sum "$1" | cut -d' ' -f1
	elif command -v shasum >/dev/null 2>&1; then
		shasum -a 256 "$1" | cut -d' ' -f1
	else
		printf 'unavailable'
	fi
}

printf '# FigTether release evidence\n'
printf '#\n'
printf '# Generated by scripts/release-evidence.sh. Values that read "unknown" or\n'
printf '# "TODO" are not filled in yet and the record is not complete.\n'
printf '\n'
printf 'commit: %s\n' "$commit"
printf 'schema_version: %s\n' "$schema_version"
printf 'protocol_version: TODO\n'
printf 'artifact_directory: %s\n' "$artifact_dir"
printf '\n'
printf '## artifact_sha256\n'
if [ -d "$artifact_dir" ]; then
	found=0
	for file in $(find "$artifact_dir" -type f | sort); do
		found=1
		printf '%s  %s\n' "$(hash_of "$file")" "$file"
	done
	if [ "$found" -eq 0 ]; then
		printf '# no files found under %s\n' "$artifact_dir"
	fi
else
	printf '# no artifact directory at %s\n' "$artifact_dir"
fi
printf '\n'
printf '## evidence fields\n'
printf 'OS/CPU/RAM: TODO\n'
printf 'Figma_version: TODO\n'
printf 'plugin_manifest_hash: TODO\n'
printf 'account_plan/seat_context: TODO\n'
printf 'fixture_hash: TODO\n'
printf 'test_id: TODO\n'
printf 'commands: TODO\n'
printf 'expected: TODO\n'
printf 'actual: TODO\n'
printf 'duration/latency/RSS: TODO\n'
printf 'network_path_evidence: TODO\n'
printf 'known_limitations: TODO\n'
printf 'reviewer: TODO\n'
printf 'tested_at: TODO\n'
