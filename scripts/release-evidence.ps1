#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Print the release evidence template for the current working tree.

.DESCRIPTION
    The PowerShell twin of scripts/release-evidence.sh. The template follows
    the release evidence template of PRD Appendix C. The commit, the artifact
    hashes, and the schema version are filled in automatically.

.EXAMPLE
    pwsh -File scripts/release-evidence.ps1 -ArtifactDirectory artifacts/release
#>

[CmdletBinding()]
param(
    [string]$ArtifactDirectory = 'artifacts/release'
)

$ErrorActionPreference = 'Stop'

$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Set-Location $Root

function Invoke-Git {
    param([string[]]$Arguments)
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $output = & git @Arguments 2>$null
        $code = $LASTEXITCODE
        return [pscustomobject]@{
            Output   = (($output | Out-String)).Trim()
            ExitCode = $code
        }
    }
    finally {
        $ErrorActionPreference = $previous
    }
}

$commit = 'unknown'
$git = Get-Command git -ErrorAction SilentlyContinue
if ($null -ne $git) {
    $inside = Invoke-Git -Arguments @('rev-parse', '--git-dir')
    if ($inside.ExitCode -eq 0 -and $inside.Output) {
        $head = Invoke-Git -Arguments @('rev-parse', '--verify', 'HEAD')
        if ($head.ExitCode -eq 0 -and $head.Output) {
            $commit = $head.Output
            $branch = Invoke-Git -Arguments @('rev-parse', '--abbrev-ref', 'HEAD')
            if ($branch.ExitCode -eq 0 -and $branch.Output) {
                $commit = "$commit (branch $($branch.Output))"
            }
        }
        else {
            $commit = 'unknown (no commit yet)'
        }
    }
}

$schemaVersion = 'unknown'
$modelLib = Join-Path $Root 'crates/model/src/lib.rs'
if (Test-Path $modelLib) {
    $match = Select-String -Path $modelLib -Pattern 'SCHEMA_VERSION:\s*&str\s*=\s*"(?<version>[^"]+)"' |
        Select-Object -First 1
    if ($null -ne $match) {
        $schemaVersion = $match.Matches[0].Groups['version'].Value
    }
}

Write-Host '# FigTether release evidence'
Write-Host '#'
Write-Host '# Generated by scripts/release-evidence.ps1. Values that read "unknown" or'
Write-Host '# "TODO" are not filled in yet and the record is not complete.'
Write-Host ''
Write-Host "commit: $commit"
Write-Host "schema_version: $schemaVersion"
Write-Host 'protocol_version: TODO'
Write-Host "artifact_directory: $ArtifactDirectory"
Write-Host ''
Write-Host '## artifact_sha256'

if (Test-Path $ArtifactDirectory) {
    $artifactRoot = (Resolve-Path $ArtifactDirectory).Path
    $files = Get-ChildItem -Path $ArtifactDirectory -Recurse -File | Sort-Object FullName
    if ($files.Count -eq 0) {
        Write-Host "# no files found under $ArtifactDirectory"
    }
    foreach ($file in $files) {
        $hash = (Get-FileHash -Path $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
        $relative = $file.FullName.Substring($artifactRoot.Length + 1)
        Write-Host "$hash  $relative"
    }
}
else {
    Write-Host "# no artifact directory at $ArtifactDirectory"
}

Write-Host ''
Write-Host '## evidence fields'
Write-Host 'OS/CPU/RAM: TODO'
Write-Host 'Figma_version: TODO'
Write-Host 'plugin_manifest_hash: TODO'
Write-Host 'account_plan/seat_context: TODO'
Write-Host 'fixture_hash: TODO'
Write-Host 'test_id: TODO'
Write-Host 'commands: TODO'
Write-Host 'expected: TODO'
Write-Host 'actual: TODO'
Write-Host 'duration/latency/RSS: TODO'
Write-Host 'network_path_evidence: TODO'
Write-Host 'known_limitations: TODO'
Write-Host 'reviewer: TODO'
Write-Host 'tested_at: TODO'
