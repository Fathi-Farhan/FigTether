fn main() -> io::Result<()> {
    let mut args = std::env::args().skip(1);
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let workspace = manifest_dir
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| manifest_dir.clone());

    let out_dir = args
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| workspace.join("schemas"));
    let model_dir = args
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| workspace.join("crates").join("model").join("src"));

    let model = verify::ModelSource::load(&model_dir)?;
    fs::create_dir_all(&out_dir)?;

    let mut written = Vec::new();
    for published in published() {
        // A fresh generator per contract keeps every file self contained:
        // the definitions of one contract never leak into the next file.
        let mut generator = SchemaSettings::draft2020_12().into_generator();
        let schema = (published.schema)(&mut generator);
        let mut value = schema.to_value();
        {
            let map = value.as_object_mut().expect("schema is an object");
            map.insert("$schema".to_string(), json!(DIALECT));
            map.insert(
                "$id".to_string(),
                json!(format!("{ID_PREFIX}{}", published.name)),
            );
        }

        let definition = model.definition(published.type_name).ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::NotFound,
                format!(
                    "the Rust model has no type named {} in {}",
                    published.type_name,
                    model_dir.display()
                ),
            )
        })?;
        verify::check(published.type_name, &value, definition, &model)?;
        verify::describe(&mut value, definition, &model);

        let path = out_dir.join(format!("{}.schema.json", published.name));
        write_schema(&path, &value)?;
        written.push((published.name, published.purpose, path));
    }

    for (name, purpose, path) in &written {
        println!("{name}: {purpose} ({})", path.display());
    }
    println!(
        "{} schema files written to {}",
        written.len(),
        out_dir.display()
    );
    Ok(())
}

/// Write one schema file as pretty printed JSON with a trailing newline.
fn write_schema(path: &Path, value: &Value) -> io::Result<()> {
    let mut text = serde_json::to_string_pretty(value).map_err(io::Error::other)?;
    text.push('\n');
    fs::write(path, text)
}
