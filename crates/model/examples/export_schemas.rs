    //! Contract mirror of the published Rust model.
    //!
    //! Every type below reproduces one type of `figtether_model`: the same
    //! field names, the same field types, the same optionality and the same
    //! serde representation. The generator verifies the mirror against the
    //! Rust model source on every run, so the mirror cannot drift silently.
    //!
    //! The mirror derives `JsonSchema` so that `schemars` produces the
    //! published files, and it derives `Serialize` and `Deserialize` so that
    //! the wire shape stays visible in one place.

