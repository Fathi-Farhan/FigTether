//! Export the published JSON Schema of every FigTether contract.
//!
//! Run it from the workspace root:
//!
//! ```text
//! cargo run -p figtether-model --example export_schemas
//! ```
//!
//! The generator writes one file per contract into `schemas/`, named
//! `<name>.schema.json`, in JSON Schema draft 2020-12. Optional arguments
//! override the output directory and the model source directory:
//!
//! ```text
//! cargo run -p figtether-model --example export_schemas -- <out-dir> <model-src-dir>
//! ```
//!
//! Where the data comes from:
//!
//! - The tool parameter schemas are generated by `schemars` from the Rust
//!   parameter types themselves, which derive `JsonSchema`.
//! - The envelope, source, observation, coverage, error, capability and
//!   normalized model schemas are generated by `schemars` from the contract
//!   mirror in the `contract` module. The mirror exists because those Rust
//!   types are published as serde contracts, not as schema deriving types.
//! - On every run the mirror is verified against the Rust model source in
//!   `crates/model/src`. A changed field, type, optionality, enum variant or
//!   doc comment makes the generator fail with a diff instead of publishing a
//!   schema that no longer matches the model.
//!
//! The published schemas therefore describe the Rust model, and the Rust model
//! stays the single source of truth.

