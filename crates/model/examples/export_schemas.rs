mod verify {
    //! Verification of the contract mirror against the Rust model source.
    //!
    //! The parser reads the Rust model sources of `crates/model/src` and
    //! extracts every public type with its fields, field types, optionality,
    //! enum variants and doc comments. The extracted model is compared with
    //! the generated schema, so a schema that no longer matches the Rust model
    //! cannot be published.

    use std::collections::BTreeMap;
    use std::fmt::Write as _;
    use std::fs;
    use std::io;
    use std::path::Path;

    use serde_json::{json, Value};

    /// Kind of a parsed type.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum Kind {
        /// A struct with named fields.
        Struct,
        /// An enum with variants.
        Enum,
        /// A tuple struct or a unit struct.
        Opaque,
    }

    /// One field of a parsed struct.
    #[derive(Debug, Clone)]
    pub struct Field {
        /// Field name.
        pub name: String,
        /// Field type as written in the source.
        pub ty: String,
        /// Doc comment of the field.
        pub doc: String,
        /// Whether the field must be present on the wire.
        pub required: bool,
    }

    /// One parsed type.
    #[derive(Debug, Clone)]
    pub struct Definition {
        /// Type name.
        pub name: String,
        /// Kind of the type.
        pub kind: Kind,
        /// Doc comment of the type.
        pub doc: String,
        /// Fields of a struct.
        pub fields: Vec<Field>,
        /// Variant names of an enum.
        pub variants: Vec<String>,
        /// Serde container attributes of the type.
        pub attrs: Vec<String>,
    }

    impl Definition {
        /// The serde name of one enum variant.
        fn variant_name(&self, variant: &str) -> String {
            match self.serde_option("rename_all").as_deref() {
                Some("snake_case") => to_snake_case(variant),
                Some("SCREAMING_SNAKE_CASE") => to_snake_case(variant).to_uppercase(),
                _ => variant.to_string(),
            }
        }

        /// One option of the serde attribute of the type.
        fn serde_option(&self, key: &str) -> Option<String> {
            for attr in &self.attrs {
                let attr = attr.trim();
                let Some(inner) = attr
                    .strip_prefix("#[serde(")
                    .and_then(|rest| rest.strip_suffix(")]"))
                else {
                    continue;
                };
                for part in inner.split(',') {
                    let part = part.trim();
                    let Some(rest) = part.strip_prefix(key) else {
                        continue;
                    };
                    let Some(value) = rest.trim_start().strip_prefix('=') else {
                        continue;
                    };
                    return Some(value.trim().trim_matches('"').to_string());
                }
            }
            None
        }
    }

    /// The parsed Rust model source.
    pub struct ModelSource {
        /// Definitions by type name.
        defs: BTreeMap<String, Definition>,
    }

    impl ModelSource {
        /// Parse every Rust file of the model source directory.
        pub fn load(dir: &Path) -> io::Result<Self> {
            let mut files: Vec<_> = fs::read_dir(dir)?
                .filter_map(|entry| entry.ok())
                .map(|entry| entry.path())
                .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
                .collect();
            files.sort();

            let mut defs = BTreeMap::new();
            for file in files {
                let text = fs::read_to_string(&file)?;
                for def in parse(&text) {
                    defs.insert(def.name.clone(), def);
                }
            }
            Ok(Self { defs })
        }

        /// Look up one type.
        pub fn definition(&self, name: &str) -> Option<&Definition> {
            self.defs.get(name)
        }
    }

    /// Compare a generated schema with the Rust model definition.
    pub fn check(
        name: &str,
        schema: &Value,
        definition: &Definition,
        model: &ModelSource,
    ) -> io::Result<()> {
        let mut problems: Vec<String> = Vec::new();

        match definition.kind {
            Kind::Struct => {
                let expected: Vec<&str> = definition
                    .fields
                    .iter()
                    .map(|field| field.name.as_str())
                    .collect();
                let actual = property_names(schema);
                if !same_set(&expected, &actual) {
                    problems.push(format!(
                        "properties differ: model has [{}], schema has [{}]",
                        expected.join(", "),
                        actual.join(", ")
                    ));
                }

                let mut expected_required: Vec<&str> = definition
                    .fields
                    .iter()
                    .filter(|field| field.required)
                    .map(|field| field.name.as_str())
                    .collect();
                expected_required.sort_unstable();
                let mut actual_required = required_names(schema);
                actual_required.sort_unstable();
                if expected_required != actual_required {
                    problems.push(format!(
                        "required differ: model has [{:?}], schema has [{:?}]",
                        expected_required, actual_required
                    ));
                }

                let properties = schema
                    .get("properties")
                    .and_then(Value::as_object)
                    .cloned()
                    .unwrap_or_default();
                for field in &definition.fields {
                    let Some(actual) = properties.get(&field.name) else {
                        continue;
                    };
                    if let Some(expected) = expected_schema(&field.ty, model) {
                        if !same_schema(&expected, actual) {
                            problems.push(format!(
                                "field {} has type {} in the model but the schema says {}",
                                field.name, field.ty, actual
                            ));
                        }
                    }
                    match (
                        actual.get("description").and_then(Value::as_str),
                        &field.doc,
                    ) {
                        (Some(actual_doc), model_doc) if actual_doc != model_doc => {
                            problems.push(format!(
                                "field {} is documented as {:?} in the model but as {:?} in the schema",
                                field.name, model_doc, actual_doc
                            ));
                        }
                        (None, model_doc) if !model_doc.is_empty() => {
                            problems.push(format!(
                                "field {} is documented in the model but has no description in the schema",
                                field.name
                            ));
                        }
                        _ => {}
                    }
                }
            }
            Kind::Enum => {
                let mut expected: Vec<String> = definition
                    .variants
                    .iter()
                    .map(|variant| definition.variant_name(variant))
                    .collect();
                expected.sort();
                let mut actual = variant_names(schema);
                actual.sort();
                if !actual.is_empty() && actual != expected {
                    problems.push(format!(
                        "variants differ: model has [{:?}], schema has [{:?}]",
                        expected, actual
                    ));
                }
            }
            Kind::Opaque => {}
        }

        if problems.is_empty() {
            Ok(())
        } else {
            let mut message = format!("the schema of {name} does not match the Rust model:\n");
            for problem in problems {
                let _ = writeln!(message, "  - {problem}");
            }
            Err(io::Error::new(io::ErrorKind::InvalidData, message))
        }
    }

    /// Add the doc comments of the Rust model to a generated schema.
    pub fn describe(schema: &mut Value, definition: &Definition, model: &ModelSource) {
        if !definition.doc.is_empty() {
            set_description(schema, &definition.doc);
        }

        if let Some(properties) = schema.get_mut("properties").and_then(Value::as_object_mut) {
            for field in &definition.fields {
                if field.doc.is_empty() {
                    continue;
                }
                if let Some(property) = properties.get_mut(&field.name) {
                    set_description(property, &field.doc);
                }
            }
        }

        if let Some(defs) = schema.get_mut("$defs").and_then(Value::as_object_mut) {
            for (key, definition) in defs.iter_mut() {
                let Some(doc) = model.definition(key).map(|def| def.doc.clone()) else {
                    continue;
                };
                if doc.is_empty() {
                    continue;
                }
                set_description(definition, &doc);
            }
        }
    }

    /// The JSON Schema fragment a Rust type must produce.
    fn expected_schema(ty: &str, model: &ModelSource) -> Option<Value> {
        let ty = normalize_type(ty);
        if let Some(inner) = ty.strip_prefix("Option<") {
            let inner = inner.strip_suffix('>')?;
            let inner = expected_schema(inner, model)?;
            return Some(nullable(inner));
        }
        if let Some(inner) = ty.strip_prefix("Vec<") {
            let inner = inner.strip_suffix('>')?;
            let inner = expected_schema(inner, model)?;
            return Some(json!({ "type": "array", "items": inner }));
        }
        if let Some(inner) = ty.strip_prefix("BTreeMap<String, ") {
            let inner = inner.strip_suffix('>')?;
            let inner = expected_schema(inner, model)?;
            return Some(json!({ "type": "object", "additionalProperties": inner }));
        }
        let schema = match ty.as_str() {
            "String" => json!({ "type": "string" }),
            "bool" => json!({ "type": "boolean" }),
            "u8" => json!({ "type": "integer", "format": "uint8", "minimum": 0, "maximum": 255 }),
            "u16" => {
                json!({ "type": "integer", "format": "uint16", "minimum": 0, "maximum": 65535 })
            }
            "u32" => json!({ "type": "integer", "format": "uint32", "minimum": 0 }),
            "u64" => json!({ "type": "integer", "format": "uint64", "minimum": 0 }),
            "u128" => json!({ "type": "integer", "format": "uint128", "minimum": 0 }),
            "usize" => json!({ "type": "integer", "format": "uint", "minimum": 0 }),
            "i8" => json!({ "type": "integer", "format": "int8", "minimum": -128, "maximum": 127 }),
            "i16" => {
                json!({ "type": "integer", "format": "int16", "minimum": -32768, "maximum": 32767 })
            }
            "i32" => json!({ "type": "integer", "format": "int32" }),
            "i64" => json!({ "type": "integer", "format": "int64" }),
            "i128" => json!({ "type": "integer", "format": "int128" }),
            "isize" => json!({ "type": "integer", "format": "int" }),
            "f32" => json!({ "type": "number", "format": "float" }),
            "f64" => json!({ "type": "number", "format": "double" }),
            "serde_json::Value" => Value::Bool(true),
            "DateTime<Utc>" | "Timestamp" => json!({ "type": "string", "format": "date-time" }),
            other => {
                let name = other.rsplit("::").next().unwrap_or(other);
                if model.definition(name).is_some() {
                    json!({ "$ref": format!("#/$defs/{name}") })
                } else {
                    return None;
                }
            }
        };
        Some(schema)
    }

    /// Allow null for one schema fragment.
    fn nullable(schema: Value) -> Value {
        let Value::Object(mut map) = schema else {
            return schema;
        };
        if map.contains_key("$ref")
            || map.contains_key("allOf")
            || map.contains_key("anyOf")
            || map.contains_key("oneOf")
        {
            return json!({ "anyOf": [Value::Object(map), { "type": "null" }] });
        }
        if let Some(kind) = map.get_mut("type") {
            let kind = kind.as_str().unwrap_or_default().to_string();
            map.insert("type".to_string(), json!([kind, "null"]));
        }
        Value::Object(map)
    }

    /// Property names of a schema, in the order of the schema object.
    fn property_names(schema: &Value) -> Vec<String> {
        schema
            .get("properties")
            .and_then(Value::as_object)
            .map(|map| map.keys().cloned().collect())
            .unwrap_or_default()
    }

    /// Required field names of a schema.
    fn required_names(schema: &Value) -> Vec<String> {
        schema
            .get("required")
            .and_then(Value::as_array)
            .map(|items| {
                items
                    .iter()
                    .filter_map(|item| item.as_str().map(str::to_string))
                    .collect()
            })
            .unwrap_or_default()
    }

    /// Variant names of an enum schema.
    ///
    /// A plain enum lists its variants in an `enum` array. A tagged enum with
    /// struct variants lists them as the constant of its tag member.
    fn variant_names(schema: &Value) -> Vec<String> {
        if let Some(defs) = schema.get("$defs").and_then(Value::as_object) {
            for definition in defs.values() {
                if let Some(items) = definition.get("enum").and_then(Value::as_array) {
                    return items
                        .iter()
                        .filter_map(|item| item.as_str().map(str::to_string))
                        .collect();
                }
            }
        }
        let mut names = Vec::new();
        for branch in schema
            .get("oneOf")
            .or_else(|| schema.get("anyOf"))
            .and_then(Value::as_array)
            .unwrap_or(&Vec::new())
        {
            let Some(properties) = branch.get("properties").and_then(Value::as_object) else {
                continue;
            };
            for property in properties.values() {
                if let Some(value) = property.get("const").and_then(Value::as_str) {
                    names.push(value.to_string());
                }
            }
        }
        names
    }

    /// Whether two schema fragments describe the same thing.
    fn same_schema(expected: &Value, actual: &Value) -> bool {
        let expected = strip(expected);
        let actual = strip(actual);
        if expected == actual {
            return true;
        }
        // An empty object schema and the boolean schema `true` both accept
        // every value, so a description alone does not change the meaning.
        let accepts_anything = matches!(&actual, Value::Object(map) if map.is_empty());
        matches!(&expected, Value::Bool(true)) && accepts_anything
    }

    /// Remove the keywords that do not change the meaning of a fragment.
    fn strip(value: &Value) -> Value {
        match value {
            Value::Object(map) => {
                let mut map = map.clone();
                map.remove("description");
                map.remove("default");
                Value::Object(map)
            }
            other => other.clone(),
        }
    }

    /// Whether two name lists hold the same names.
    fn same_set(expected: &[&str], actual: &[String]) -> bool {
        if expected.len() != actual.len() {
            return false;
        }
        let mut actual: Vec<&str> = actual.iter().map(String::as_str).collect();
        actual.sort_unstable();
        let mut expected = expected.to_vec();
        expected.sort_unstable();
        expected == actual
    }

    /// Set the description of a schema fragment.
    fn set_description(schema: &mut Value, doc: &str) {
        if schema.is_object() {
            if let Some(map) = schema.as_object_mut() {
                if !map.contains_key("description") {
                    map.insert("description".to_string(), Value::String(doc.to_string()));
                }
            }
            return;
        }
        if schema.is_boolean() {
            *schema = json!({ "description": doc });
        }
    }

    /// Normalize a type text so that paths do not matter.
    fn normalize_type(ty: &str) -> String {
        ty.replace("chrono::", "")
    }

    /// Convert a CamelCase name to snake_case.
    fn to_snake_case(name: &str) -> String {
        let mut out = String::with_capacity(name.len() + 4);
        for (index, character) in name.chars().enumerate() {
            if character.is_uppercase() {
                if index > 0 {
                    out.push('_');
                }
                out.extend(character.to_lowercase());
            } else {
                out.push(character);
            }
        }
        out
    }

    /// Parse every public type of one Rust source file.
    fn parse(text: &str) -> Vec<Definition> {
        let mut defs: Vec<Definition> = Vec::new();
        let mut pending_doc: Vec<String> = Vec::new();
        let mut pending_attrs: Vec<String> = Vec::new();
        let mut current: Option<Definition> = None;
        let mut state = State::Top;

        for line in text.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() {
                continue;
            }
            if let Some(rest) = trimmed.strip_prefix("///") {
                pending_doc.push(rest.strip_prefix(' ').unwrap_or(rest).to_string());
                continue;
            }
            if trimmed.starts_with("#[") {
                pending_attrs.push(trimmed.to_string());
                continue;
            }
            if trimmed.starts_with("//") {
                continue;
            }

            match state {
                State::Top => {
                    if let Some((name, kind)) = type_start(trimmed) {
                        if let Some(previous) = current.take() {
                            defs.push(previous);
                        }
                        current = Some(Definition {
                            name,
                            kind,
                            doc: join_doc(&pending_doc),
                            fields: Vec::new(),
                            variants: Vec::new(),
                            attrs: pending_attrs.clone(),
                        });
                        pending_doc.clear();
                        pending_attrs.clear();
                        state = match kind {
                            Kind::Struct => State::Struct,
                            Kind::Enum => State::Enum,
                            Kind::Opaque => State::Top,
                        };
                    } else if let Some((name, doc)) = id_type_start(trimmed) {
                        defs.push(Definition {
                            name,
                            kind: Kind::Opaque,
                            doc,
                            fields: Vec::new(),
                            variants: Vec::new(),
                            attrs: Vec::new(),
                        });
                    }
                }
                State::Struct => {
                    if trimmed == "}" {
                        if let Some(previous) = current.take() {
                            defs.push(previous);
                        }
                        state = State::Top;
                        continue;
                    }
                    if let Some((name, ty)) = field_start(trimmed) {
                        let has_default = pending_attrs.iter().any(|attr| attr.contains("default"));
                        let required = !has_default && !ty.starts_with("Option<");
                        if let Some(definition) = current.as_mut() {
                            definition.fields.push(Field {
                                name,
                                ty,
                                doc: join_doc(&pending_doc),
                                required,
                            });
                        }
                        pending_doc.clear();
                        pending_attrs.clear();
                    }
                }
                State::Enum => {
                    if trimmed == "}" {
                        if let Some(previous) = current.take() {
                            defs.push(previous);
                        }
                        state = State::Top;
                        continue;
                    }
                    if let Some(variant) = variant_start(trimmed) {
                        if let Some(definition) = current.as_mut() {
                            definition.variants.push(variant);
                        }
                        pending_doc.clear();
                        pending_attrs.clear();
                        if trimmed.ends_with('{') {
                            state = State::Variant;
                        }
                    }
                }
                State::Variant => {
                    if trimmed == "}," || trimmed == "}" {
                        state = State::Enum;
                    }
                }
            }
        }

        if let Some(last) = current.take() {
            defs.push(last);
        }
        defs
    }

    /// Parser state.
    enum State {
        /// Outside a type.
        Top,
        /// Inside the fields of a struct.
        Struct,
        /// Inside the variants of an enum.
        Enum,
        /// Inside the fields of a struct variant.
        Variant,
    }

    /// Detect the start of a public type.
    fn type_start(line: &str) -> Option<(String, Kind)> {
        if let Some(rest) = line.strip_prefix("pub struct ") {
            let name = rest
                .split(['{', '(', ';', ' '])
                .next()
                .unwrap_or_default()
                .to_string();
            let kind = if rest.contains('(') {
                Kind::Opaque
            } else {
                Kind::Struct
            };
            return Some((name, kind));
        }
        if let Some(rest) = line.strip_prefix("pub enum ") {
            let name = rest
                .split(['{', ' '])
                .next()
                .unwrap_or_default()
                .to_string();
            return Some((name, Kind::Enum));
        }
        None
    }

    /// Detect an identifier newtype produced by the `id_type!` macro.
    fn id_type_start(line: &str) -> Option<(String, String)> {
        let rest = line.strip_prefix("id_type!(")?;
        let (name, rest) = rest.split_once(',')?;
        let doc = rest
            .trim()
            .trim_start_matches('"')
            .split('"')
            .next()
            .unwrap_or_default()
            .to_string();
        Some((name.trim().to_string(), doc))
    }

    /// Detect the start of a struct field.
    fn field_start(line: &str) -> Option<(String, String)> {
        let rest = line.strip_prefix("pub ")?;
        let (name, ty) = rest.split_once(':')?;
        let name = name.trim();
        if name.is_empty() || !name.chars().all(|c| c.is_alphanumeric() || c == '_') {
            return None;
        }
        let ty = ty.trim().trim_end_matches(',').trim().to_string();
        Some((name.to_string(), ty))
    }

    /// Detect the start of an enum variant.
    fn variant_start(line: &str) -> Option<String> {
        let name: String = line
            .chars()
            .take_while(|c| c.is_alphanumeric() || *c == '_')
            .collect();
        if name.is_empty() || !name.chars().next().is_some_and(char::is_uppercase) {
            return None;
        }
        Some(name)
    }

    /// Join doc comment lines.
    fn join_doc(lines: &[String]) -> String {
        lines.join("\n")
    }
}

